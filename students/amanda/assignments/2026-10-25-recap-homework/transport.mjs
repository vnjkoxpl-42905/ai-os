import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const home = path.dirname(fileURLToPath(import.meta.url));
const vault = 'C:/Users/Joshu/dev/ai-os';
const ops = 'C:/Users/Joshu/dev/ai-os-projects/.lsatu-ops-amanda-20261025';
const commit = '6a167c8555b4a404334310aad48a5d748b1b0861';
const plugin = 'supabase/functions/mcp/index.ts';
const args = process.argv.slice(2);
if (args.some(a => /[\r\n]/.test(a))) throw new Error('Multiline arguments refused');
const guided = args.indexOf('--guided-file');
const dryRun = args.includes('--dry-run');
const label = guided >= 0 ? 'guided' : args.includes('--bootcamp') ? 'unless' : 'general-conditionals';
const run = (cmd, argv, cwd = vault) => execFileSync(cmd, argv, { cwd, encoding: 'utf8', windowsHide: true, timeout: 180000, maxBuffer: 4 * 1024 * 1024, env: { ...process.env, TZ: 'America/Toronto' } });
const git = (...argv) => run('git', ['-C', ops, ...argv]).trim();
if (git('rev-parse', 'HEAD') !== commit || git('rev-parse', 'origin/main') !== commit) throw new Error('Pinned checkout differs from verified origin/main');
if (git('status', '--porcelain', '--untracked-files=no')) throw new Error('Tracked checkout edits: refusing');
const pluginBefore = fs.readFileSync(path.join(ops, plugin), 'utf8');
const expectedPlugin = `// AUTO-GENERATED by @lovable.dev/mcp-js — do not edit. Regenerated by the Vite plugin.\n// To take ownership, delete this banner line; the plugin then leaves the file alone.\n// supabase function: mcp\n// Bundled from src/lib/mcp/index.ts by @lovable.dev/mcp-js.\n// lovable-mcp-supabase-entry.ts\nimport mcp from ${JSON.stringify('npm:' + path.join(ops, 'src/lib/mcp/index.ts'))};\nimport { createSupabaseHandler } from "npm:@lovable.dev/mcp-js@0.20.0/stacks/supabase";\nDeno.serve(createSupabaseHandler(mcp, { functionName: "mcp" }));\n`;
let output = '', failed;
try {
  let runnerArgs;
  if (guided >= 0) {
    const file = path.resolve(vault, args[guided + 1]);
    const source = fs.readFileSync(path.join(vault, 'system/scripts/lsatu-guided-plan.ts'), 'utf8');
    if (source.split("'__VAULT_ROOT__'").length !== 2) throw new Error('Guided placeholder changed');
    const relative = 'scripts/.ai-os-guided-plan.generated.ts';
    const exclude = path.resolve(ops, git('rev-parse', '--git-path', 'info/exclude'));
    const old = fs.readFileSync(exclude, 'utf8');
    if (!old.split(/\r?\n/).includes('/' + relative)) fs.appendFileSync(exclude, '\n/' + relative + '\n');
    fs.writeFileSync(path.join(ops, relative), source.replace("'__VAULT_ROOT__'", JSON.stringify(vault)));
    runnerArgs = [relative, '--', '--file', file, ...(dryRun ? ['--dry-run'] : [])];
  } else {
    if (!args.includes('--bootcamp') && !args.includes('--activity')) throw new Error('Supported: --guided-file, --bootcamp, or --activity');
    run(process.execPath, [path.join(vault, 'system/scripts/prepare-assign.mjs'), ops]);
    runnerArgs = ['scripts/.ai-os-assign.generated.ts', '--', ...args];
  }
  output = run(process.execPath, ['node_modules/vite-node/vite-node.mjs', ...runnerArgs], ops);
} catch (e) {
  output = String(e.stdout || '') + '\n' + String(e.stderr || '') + '\n' + e.message;
  failed = e;
} finally {
  const dirty = git('diff', '--name-only').split(/\r?\n/).filter(Boolean);
  if (dirty.length) {
    const after = fs.readFileSync(path.join(ops, plugin), 'utf8');
    if (dirty.length !== 1 || dirty[0] !== plugin || after.replace(/\r\n/g, '\n') !== expectedPlugin) throw new Error('Unexpected tracked changes; preserved for inspection');
    git('restore', '--', plugin);
  }
  if (git('status', '--porcelain', '--untracked-files=no')) throw new Error('Checkout not clean after execution');
}
const evidence = { checked_at: new Date().toISOString(), commit, dry_run: dryRun, args, source_sha256: createHash('sha256').update(fs.readFileSync(path.join(vault, guided >= 0 ? 'system/scripts/lsatu-guided-plan.ts' : 'system/scripts/prepare-assign.mjs'))).digest('hex'), output, success: !failed };
const stamp = new Date().toISOString().replace(/[:.]/g, '-');
fs.writeFileSync(path.join(home, `${label}-${dryRun ? 'preview' : 'assignment'}-${stamp}.json`), JSON.stringify(evidence, null, 2));
process.stdout.write(output);
if (failed) process.exitCode = 1;
