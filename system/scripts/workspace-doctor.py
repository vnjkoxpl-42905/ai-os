ROOT = Path(__file__).resolve().parents[2]
HOME = Path.home()
MARKER = '<!-- generated by workspace-doctor.py; do not edit -->'

@dataclass(frozen=True)
class Finding:
    check: str
    state: str
    evidence: str
    action: str


def parse_time(value):
    if not isinstance(value, str) or 'T' not in value:
        return None
    try:
        parsed = datetime.fromisoformat(value.replace('Z', '+00:00'))
        return parsed if parsed.tzinfo else None
    except ValueError:
        return None


def receipt_finding(data, now):
    stamp = parse_time(data.get('last_success')) if isinstance(data, dict) else None
    if not stamp:
        return Finding('GitHub snapshot receipt', 'unknown', 'No valid last_success timestamp in status.json.', 'Inspect the sync receipt and run history before relying on snapshots.')
    age = now - stamp
    if age < timedelta(minutes=-5):
        return Finding('GitHub snapshot receipt', 'warning', 'Last success timestamp is in the future.', 'Check the laptop clock and receipt.')
    if age > timedelta(hours=24):
        return Finding('GitHub snapshot receipt', 'warning', f'Last recorded success: {stamp.isoformat()} (older than 24 hours).', 'Inspect scheduler and sync failures before relying on freshness.')
    return Finding('GitHub snapshot receipt', 'healthy', f'Last recorded success: {stamp.isoformat()}.', 'Keep monitoring; receipt alone does not prove restore.')



def runner_finding(data, now):
    outcome = data.get('outcome') if isinstance(data, dict) else None
    if outcome in ('deferred', 'failed', 'error'):
        return Finding('Latest combined sync run', 'warning', f'The latest combined runner receipt reports {outcome}.', 'Inspect scheduler and receipt before relying on current sync.')
    if outcome != 'succeeded':
        return Finding('Latest combined sync run', 'unknown', 'Combined runner outcome is missing or unrecognized.', 'Inspect the runner receipt.')
    stamp = parse_time(data.get('completed_utc'))
    if not stamp:
        return Finding('Latest combined sync run', 'unknown', 'A successful runner receipt lacks a valid completion timestamp.', 'Inspect the runner receipt and scheduler history.')
    age = now - stamp
    if age < timedelta(minutes=-5) or age > timedelta(hours=24):
        return Finding('Latest combined sync run', 'warning', f'Last combined success: {stamp.isoformat()}; outside the 24-hour freshness window.', 'Inspect the scheduler and run history before relying on sync.')
    return Finding('Latest combined sync run', 'healthy', f'Last combined success: {stamp.isoformat()}.', 'Check scheduler state and restore independently.')

def checkpoint_finding(text, now):
    match = re.search(r'^- \*\*Checkpoint time:\*\*\s*(.*)$', text, re.M)
    value = match.group(1).strip() if match else ''
    stamp = parse_time(value)
    if not stamp:
        return Finding('Pilot checkpoint freshness', 'unknown', 'No exact ISO 8601 timestamp with time zone in the checkpoint.', 'Record the exact time and offset on ownership yield.')
    age = now - stamp
    if age < timedelta(minutes=-5) or age > timedelta(days=7):
        return Finding('Pilot checkpoint freshness', 'warning', f'Checkpoint time: {stamp.isoformat()}; outside the seven-day freshness window.', 'Verify branch, HEAD, changes and ownership, then refresh the checkpoint.')
    return Finding('Pilot checkpoint freshness', 'healthy', f'Checkpoint time: {stamp.isoformat()}.', 'Still verify branch, HEAD and ownership before resuming.')


def policy_finding(a, b):
    def section(text, name):
        match = re.search(r'^## ' + re.escape(name) + r'\s*\n(.*?)(?=^## |\Z)', text, re.M | re.S)
        return match.group(1).replace('\r\n', '\n').strip() if match else None
    names = ['Routing map', 'Guardrails']
    missing = [n for n in names if section(a, n) is None or section(b, n) is None]
    drift = [n for n in names if n not in missing and section(a, n) != section(b, n)]
    if missing:
        return Finding('Shared policy', 'unknown', 'A required comparison section is absent.', 'Inspect AGENTS.md and CLAUDE.md before comparing policy.')
    if drift:
        return Finding('Shared policy', 'warning', 'Shared sections differ: ' + ', '.join(drift) + '.', 'Compare the shared sections and resolve intentional versus accidental drift.')
    return Finding('Shared policy', 'healthy', 'Routing map and Guardrails match after line-ending normalization.', 'Continue maintaining both shared sections together.')


def hook_targets(commands, exists):
    # Examine explicit absolute targets. Any remaining file-like argument that
    # cannot be resolved safely makes the result unknown, even if others exist.
    absolute = re.compile(r"(?i)[a-z]:[\\/][^'\"\r\n]*?\.(?:ps1|py|cmd|bat|exe)\b")
    tokens = re.compile(r"(?i)(?<![a-z0-9_./\\:-])[a-z0-9_./\\:-]+\.(?:ps1|py|cmd|bat|exe)\b")
    missing, uncheckable, count = 0, 0, 0
    for command in commands:
        targets = list(absolute.finditer(command))
        for target in targets:
            count += 1
            if not exists(target.group()):
                missing += 1
        uncertain = not targets
        for token in tokens.finditer(command):
            if any(target.start() <= token.start() and token.end() <= target.end() for target in targets):
                continue
            value = token.group()
            # Resolve only an unqualified executable on PATH; a relative script
            # is not anchored by the command's working directory here.
            if value.lower().endswith('.exe') and '/' not in value and '\\' not in value and shutil.which(value):
                continue
            uncertain = True
        if uncertain:
            uncheckable += 1
    if missing:
        return Finding('Explicit hook targets', 'failed', f'{missing} of {count} explicit targets are missing.', 'Inspect configured hooks and repair missing targets without bypassing review.')
    if uncheckable:
        return Finding('Explicit hook targets', 'unknown', f'{count} explicit targets exist; {uncheckable} commands could not be fully resolved statically.', 'Review dynamic or relative commands and their interpreters manually.')
    if not commands:
        return Finding('Explicit hook targets', 'unknown', 'No explicit hooks found in inspected files.', 'Confirm hook discovery covers the intended runtime settings.')
    return Finding('Explicit hook targets', 'healthy', f'All {count} explicit script and interpreter targets in inspected hooks exist.', 'Review approvals through the supported UI and test native sessions separately.')


def hook_commands(obj):
    found = []
    def visit(x):
        if isinstance(x, dict):
            if x.get('type') == 'command' and isinstance(x.get('command'), str):
                found.append(x['command'])
            for v in x.values():
                visit(v)
        elif isinstance(x, list):
            for v in x:
                visit(v)
    if isinstance(obj, dict):
        visit(obj.get('hooks', {}))
    return found


def settings_findings(root, home):
    files = [(home/'.codex/hooks.json', 'json', True), (home/'.codex/config.toml', 'toml', True),
             (home/'.claude/settings.json', 'json', True), (root/'.codex/hooks.json', 'json', True),
             (root/'.codex/config.toml', 'toml', True), (root/'.claude/settings.json', 'json', True),
             (root/'.claude/settings.local.json', 'json', False)]
    commands, invalid, missing = [], [], []
    for path, kind, required in files:
        if not path.exists():
            if required: missing.append(path.name)
            continue
        try:
            data = json.loads(path.read_text(encoding='utf-8-sig')) if kind == 'json' else tomllib.loads(path.read_text(encoding='utf-8-sig'))
            if not isinstance(data, dict): raise ValueError('not object')
            if kind == 'json': commands.extend(hook_commands(data))
        except (OSError, ValueError, tomllib.TOMLDecodeError):
            invalid.append(path.name)
    if invalid:
        status = Finding('Settings syntax', 'failed', f'{len(invalid)} inspected settings files are invalid or unreadable.', 'Inspect the affected runtime settings; do not change security settings blindly.')
    elif missing:
        status = Finding('Settings syntax', 'unknown', f'{len(missing)} expected settings files were absent.', 'Verify the runtime installation and expected settings locations.')
    else:
        status = Finding('Settings syntax', 'healthy', 'Inspected JSON and TOML settings parse as objects.', 'Syntax validation does not establish hook approval or runtime behavior.')
    return status, hook_targets(commands, lambda p: Path(p).is_file())


def skill_finding(returncode):
    if returncode == 0:
        return Finding('Skill parity validator', 'healthy', 'Existing check-skills.py passed, including declared runtime differences.', 'Maintain skills/PARITY.md when differences change.')
    if returncode == 1:
        return Finding('Skill parity validator', 'failed', 'Existing check-skills.py reported one or more problems.', 'Run python system/scripts/check-skills.py locally to inspect its findings.')
    return Finding('Skill parity validator', 'unknown', 'The existing validator did not complete normally.', 'Run python system/scripts/check-skills.py locally and inspect its exit status.')


def collect(root=ROOT, home=HOME):
    now = datetime.now(timezone.utc)
    out = []
    out.extend(settings_findings(root, home))
    try:
        out.append(policy_finding((root/'AGENTS.md').read_text(encoding='utf-8'), (root/'CLAUDE.md').read_text(encoding='utf-8')))
    except OSError:
        out.append(Finding('Shared policy', 'unknown', 'Could not read both root policy files.', 'Check AGENTS.md and CLAUDE.md accessibility.'))
    try:
        result = subprocess.run([sys.executable, '-B', str(root/'system/scripts/check-skills.py')], cwd=root, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=120)
        out.append(skill_finding(result.returncode))
    except (OSError, subprocess.TimeoutExpired):
        out.append(skill_finding(None))
    # LSAT U candidates are intentionally both checked until their mapping is settled.
    paths = [('AI OS', root), ('Job Search', home/'dev/ai-job-search'), ('LSAT U navigation home', home/'dev/lsatu'), ('LSAT U worktree hub', home/'dev/ai-os-projects/lsatu')]
    for name, path in paths:
        if path.is_dir():
            out.append(Finding(name + ' path', 'healthy', 'Directory exists.', 'Verify Git state before choosing or editing a checkout.'))
        else:
            out.append(Finding(name + ' path', 'failed', 'Expected directory is absent or inaccessible.', 'Reconcile the project mapping before resuming work.'))
    checkpoint = root/'brainstorms/2026-11-14-workspace-redesign-checkpoint.md'
    try:
        out.append(checkpoint_finding(checkpoint.read_text(encoding='utf-8'), now))
    except OSError:
        out.append(Finding('Pilot checkpoint freshness', 'unknown', 'Pilot checkpoint is unavailable.', 'Locate or create the intended checkpoint before switching agents.'))
    try:
        data = json.loads((root/'setup/github-sync/state/status.json').read_text(encoding='utf-8'))
        out.append(receipt_finding(data, now))
    except (OSError, ValueError):
        out.append(receipt_finding({}, now))
    try:
        run = json.loads((root/'setup/github-sync/state/runner-status.json').read_text(encoding='utf-8'))
        out.append(runner_finding(run, now))
    except (OSError, ValueError):
        out.append(runner_finding({}, now))
    return now, out


def render(now, findings):
    lines = [MARKER, '# Workspace health report', '', 'Generated: ' + now.isoformat(), '', 'Read-only checks. A receipt is not proof of a working schedule or a successful restore.', '', '| Check | State | Evidence | Next action |', '|---|---|---|---|']
    for f in findings:
        cells = [f.check, f.state.upper(), f.evidence, f.action]
        lines.append('| ' + ' | '.join(c.replace('|', '\\|').replace('\n', ' ') for c in cells) + ' |')
    lines.extend(['', 'Scope: explicit global and AI OS settings only. Other project and plugin hooks, live approval state, network state, native chat history and backup restoration are not checked.', 'Report writing uses a cooperative lock and a comparison immediately before replacement. A writer that ignores the lock can still race with replacement.', ''])
    return '\n'.join(lines)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def current(path):
    try: return path.read_bytes()
    except FileNotFoundError: return None


@contextmanager
def report_lock(lock):
    # A stable ignored machine-state file serializes this generator; never removed.
    lock.parent.mkdir(parents=True, exist_ok=True)
    with lock.open('a+b') as f:
        if os.name == 'nt':
            import msvcrt
            if f.tell() == 0: f.write(b'0'); f.flush()
            f.seek(0); msvcrt.locking(f.fileno(), msvcrt.LK_LOCK, 1)
            try: yield
            finally: f.seek(0); msvcrt.locking(f.fileno(), msvcrt.LK_UNLCK, 1)
        else:
            import fcntl
            fcntl.flock(f, fcntl.LOCK_EX)
            try: yield
            finally: fcntl.flock(f, fcntl.LOCK_UN)


def write_report(path, expected, body, lock_path=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    lock_path = lock_path or ROOT/'setup/github-sync/state/workspace-doctor.lock'
    with report_lock(lock_path):
        before = current(path)
        actual = 'absent' if before is None else digest(before)
        if actual != expected:
            raise RuntimeError('Report changed since it was read; refusing to overwrite.')
        if before is not None and not before.startswith(MARKER.encode()):
            raise RuntimeError('Existing report lacks generated marker; refusing to overwrite.')
        fd, temporary = tempfile.mkstemp(prefix='workspace-health-', suffix='.tmp', dir=path.parent)
        with os.fdopen(fd, 'wb') as f:
            f.write(body.encode('utf-8')); f.flush(); os.fsync(f.fileno())
        if current(path) != before:
            raise RuntimeError('Report changed during preparation; prepared file retained.')
        os.replace(temporary, path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Write generated report with cooperative locking and compare-before-replace')
    args = parser.parse_args()
    target = ROOT/'system/generated/workspace-health.md'
    prior = current(target)
    expected = 'absent' if prior is None else digest(prior)
    now, findings = collect()
    report = render(now, findings)
    if args.write:
        try: write_report(target, expected, report)
        except (OSError, RuntimeError) as exc:
            print('Report not written: ' + str(exc), file=sys.stderr); return 2
    print(report)
    return 1 if any(f.state == 'failed' for f in findings) else 0

if __name__ == '__main__':
    raise SystemExit(main())
