#!/usr/bin/env python3
"""Phase 3: generate brain/skills/INDEX.md — one line per DB skill,
grouped by source-type, nested within the claude/ and codex/ split."""
import io, os, re, sys, tempfile
from pathlib import Path

BRAIN = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DB = f"{BRAIN}/skills"

def read_desc(skill_dir):
    sk = os.path.join(skill_dir, "SKILL.md")
    if not os.path.isfile(sk):
        # resolve symlink dir
        return "", "no SKILL.md"
    try:
        with open(sk, encoding="utf-8", errors="replace") as f:
            txt = f.read()
    except OSError:
        return "", "unreadable"
    m = re.search(r"(?ms)^---\s*\n(.*?)\n---", txt)
    fm = m.group(1) if m else txt[:800]
    dm = re.search(r"(?mi)^description:\s*(.*)$", fm)
    if not dm:
        return "", "no description"
    d = dm.group(1).strip()
    if d in (">", "|", ">-", "|-", ""):
        # folded / literal block scalar: gather the indented lines that follow
        rest = fm[dm.end():]
        block = []
        for line in rest.splitlines():
            if line.startswith((" ", "	")):
                block.append(line.strip())
            elif line.strip() == "":
                continue
            else:
                break
        d = " ".join(block)
    d = d.strip().strip('"').strip("'")
    d = re.sub(r"\s+", " ", d)
    return d, ""

def classify(sub, name, path):
    if os.path.islink(path):
        return "vendor-plugin"
    return "authored"

def scan(sub):
    base = os.path.join(DB, sub)
    entries = []          # (name, source_type, desc, weak)
    forks = []            # (proj, name, desc, weak)
    for name in sorted(os.listdir(base)):
        p = os.path.join(base, name)
        if name in ("README.md", "INDEX.md"): continue
        if name == "_snapshots": continue
        if name == "_inactive": continue
        if name == "_project-forks":
            for proj in sorted(os.listdir(p)):
                pp = os.path.join(p, proj)
                if not os.path.isdir(pp): continue
                for fn in sorted(os.listdir(pp)):
                    fpp = os.path.join(pp, fn)
                    if not (os.path.isdir(fpp) or os.path.islink(fpp)): continue
                    d, w = read_desc(fpp)
                    forks.append((proj, fn, d, w))
            continue
        if not (os.path.isdir(p) or os.path.islink(p)): continue
        st = classify(sub, name, p)
        d, w = read_desc(p)
        entries.append((name, st, d, w))
    return entries, forks

def emit(f, sub):
    entries, forks = scan(sub)
    authored = [e for e in entries if e[1] == "authored"]
    vendor   = [e for e in entries if e[1] == "vendor-plugin"]
    # Google Workspace (gws-*) skills get their own section within authored.
    gws      = [e for e in authored if e[0].startswith("gws-")]
    authored = [e for e in authored if not e[0].startswith("gws-")]
    f.write(f"\n## {sub}/\n")
    f.write(f"\n{len(authored)} authored/project · {len(gws)} google-workspace · "
            f"{len(vendor)} vendor-plugin · {sum(1 for _, _, _, w in forks if w != 'no SKILL.md')} project-fork\n")
    if gws:
        f.write("\n### Google Workspace (gws) skills\n\n")
        f.write("_Full `gws` CLI skill set. Inert in the DB. Copy selected skills into "
                f"the project's `{'.claude' if sub == 'claude' else '.gemini' if sub == 'gemini' else '.agents'}/skills/` to activate. Global availability depends on explicit installation._\n\n")
        for n, st, d, w in gws:
            f.write(f"- **{n}** — {d or '_(' + w + ')_'}\n")
    if authored:
        f.write("\n### Authored / project skills\n\n")
        for n, st, d, w in authored:
            f.write(f"- **{n}** — {d or '_(' + w + ')_'}\n")
    if vendor:
        f.write("\n### Vendor / plugin skills (live symlink + snapshot)\n\n")
        for n, st, d, w in vendor:
            f.write(f"- **{n}** — {d or '_(' + w + ')_'}\n")
    support = [(proj, n) for proj, n, d, w in forks if w == "no SKILL.md"]
    forks = [(proj, n, d, w) for proj, n, d, w in forks if w != "no SKILL.md"]
    if forks:
        f.write("\n### Project forks (divergent project-local versions)\n\n")
        for proj, n, d, w in forks:
            f.write(f"- **{proj}: {n}** — {d or '_(' + w + ')_'}\n")
    if support:
        f.write("\n### Archived project support folders (not invokable skills)\n\n")
        for proj, n in support:
            f.write(f"- [{proj}/{n}]({sub}/_project-forks/{proj}/{n}/): preserved supporting files; no SKILL.md entry point.\n")
    return entries, forks

def main():
    out = os.path.join(DB, "INDEX.md")
    output = Path(out)
    original = output.read_bytes() if output.exists() else None
    weak = []
    with io.StringIO() as f:
        f.write("# Skill index\n\n")
        f.write("One line per skill in the master DB, grouped by source-type within the "
                "`claude/`, `codex/` and `gemini/` split. Generated by `system/scripts/gen-skill-index.py` — do not hand-edit.\n")
        for sub in ("claude", "codex", "gemini"):
            entries, forks = emit(f, sub)
            for n, st, d, w in entries:
                if w: weak.append(f"{sub}/{n}: {w}")
            for proj, n, d, w in forks:
                if w: weak.append(f"{sub}/_project-forks/{proj}/{n}: {w}")
        generated = f.getvalue().encode("utf-8")
    if generated != original:
        with tempfile.NamedTemporaryFile(dir=output.parent, prefix=".skill-index-", suffix=".tmp", delete=False) as stage:
            stage.write(generated)
            staged = Path(stage.name)
        try:
            current = output.read_bytes() if output.exists() else None
            if current != original:
                raise RuntimeError("INDEX.md changed during generation; regenerate from current files")
            os.replace(staged, output)
        finally:
            if staged.exists():
                staged.unlink()
    print(f"Wrote {out}")
    if weak:
        print(f"\n{len(weak)} entries with missing/weak descriptions (hand-write these):")
        for w in weak:
            print("  " + w)

if __name__ == "__main__":
    main()
