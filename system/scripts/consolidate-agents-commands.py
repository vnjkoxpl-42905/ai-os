#!/usr/bin/env python3
"""Convert catalogued Claude agents into project-scoped Codex agent TOML files.

Claude plugin agents are preserved in agents/claude/_snapshots. Codex equivalents
use collision-safe catalog filenames as their names, inherit the parent model and
reasoning settings, and are activated by copying them into .codex/agents.
"""

from __future__ import annotations

import json
import re
import shutil
import tomllib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
CLAUDE_SNAPSHOTS = ROOT / "agents" / "claude" / "_snapshots"
CODEX_CATALOG = ROOT / "agents" / "codex"
CODEX_ACTIVE = ROOT / ".codex" / "agents"


def parse_agent(path: Path) -> tuple[dict[str, str], str]:
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\s*\n(.*?)\n---\s*\n?(.*)\Z", text, re.S)
    if not match:
        raise ValueError(f"missing YAML frontmatter: {path}")
    header, body = match.groups()
    fields: dict[str, str] = {}
    for line in header.splitlines():
        key, sep, value = line.partition(":")
        if sep:
            fields[key.strip()] = value.strip().strip('"').strip("'")
    if fields.get("description") in {"|", ">"}:
        block = re.search(r"(?ms)^description:\s*[|>]\s*\n((?:[ \t]+.*(?:\n|$))*)", header)
        if block:
            fields["description"] = " ".join(
                line.strip() for line in block.group(1).splitlines() if line.strip()
            )
    return fields, body.strip() + "\n"


def codex_name(stem: str) -> str:
    return re.sub(r"[^a-z0-9_]+", "_", stem.lower()).strip("_")


def convert(path: Path) -> Path:
    fields, body = parse_agent(path)
    name = codex_name(path.stem)
    description = fields.get("description") or f"Codex equivalent of {path.stem}."
    tools = fields.get("tools", "")
    sandbox = "workspace-write" if re.search(r"\b(?:Write|Edit)\b", tools) else "read-only"
    body = body.replace("CLAUDE.md", "AGENTS.md")
    body = body.replace("Claude Code", "Codex")
    content = (
        f"name = {json.dumps(name)}\n"
        f"description = {json.dumps(description)}\n"
        f"sandbox_mode = {json.dumps(sandbox)}\n\n"
        f"developer_instructions = {json.dumps(body)}\n"
    )
    output = CODEX_CATALOG / f"{path.stem}.toml"
    output.write_text(content, encoding="utf-8", newline="\n")
    with output.open("rb") as handle:
        parsed = tomllib.load(handle)
    for required in ("name", "description", "developer_instructions"):
        if not parsed.get(required):
            raise ValueError(f"{output} lacks required field {required}")
    return output


def write_index() -> None:
    claude = sorted(p for p in (ROOT / "agents" / "claude").glob("*.md"))
    codex = sorted(p for p in CODEX_CATALOG.glob("*.toml"))
    lines = [
        "# Agents index",
        "",
        "Generated by `system/scripts/consolidate-agents-commands.py`.",
        "",
        f"## Claude ({len(claude)})",
        "",
    ]
    lines.extend(f"- `{p.name}`" for p in claude)
    lines.extend(["", f"## Codex ({len(codex)})", ""])
    for path in codex:
        with path.open("rb") as handle:
            data = tomllib.load(handle)
        lines.append(f"- `{path.name}`: {data.get('description', '')}")
    lines.append("")
    (ROOT / "agents" / "INDEX.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> None:
    CODEX_CATALOG.mkdir(parents=True, exist_ok=True)
    CODEX_ACTIVE.mkdir(parents=True, exist_ok=True)
    generated = [convert(path) for path in sorted(CLAUDE_SNAPSHOTS.glob("*.md"))]
    active_sources = sorted(CODEX_CATALOG.glob("*.toml"))
    for path in active_sources:
        shutil.copy2(path, CODEX_ACTIVE / path.name)
    write_index()
    print(f"agents: PASS (converted={len(generated)}; activated={len(active_sources)})")


if __name__ == "__main__":
    main()
